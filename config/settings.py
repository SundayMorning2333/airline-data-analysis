# 数据库连接池配置
# 注意：超时配置针对大批量数据操作做了优化
# - read_timeout/write_timeout 须大于最慢单条 SQL 的执行时间，否则会被强制断连
# - 5M 行 CSV 批量导入可能耗时数分钟，故写超时设置为 600s
# - maxusage 调大避免频繁创建/销毁连接
